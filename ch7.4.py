print(" *** Snake case / Camel case / Pascal case / Kebab case ***")
x = input("Enter words : ")
x = x.split(" ")
snake = "_".join([i.lower() for i in x])
pascal = "".join([i.capitalize() for i in x])
camel = x[0].lower() +"".join([i.capitalize() for i in x[1:]])
kebab = "-".join([i.lower() for i in x])
print("Snake case  =",snake)
print("Camel case  =",camel)
print("Pascal case =",pascal)
print("Kebab case  =",kebab)
print("===== End of program =====")